R = Prior.R
read, save, sha, digest, np, torch = Prior.read, Prior.save, Prior.sha, Prior.digest, Prior.np, Prior.torch


def plan():
    return read(HERE / 'protocol.json')


def verify(p, *args):
    assert p['authorization_approved'] and time.time() < p['absolute_all_stop']
    assert (HERE / 'protocol.json').read_bytes() == (OUT / 'protocol.json').read_bytes()
    assert R.used(OUT) <= p['max_bytes']
    assert R.used(ROOT / 'stage/runs') - R.used(OUT) + p['max_bytes'] < p['global_bytes']
    assert shutil.disk_usage(ROOT).free >= 40 * 2**30
    assert os.environ.get('CUDA_VISIBLE_DEVICES') == '' and not torch.cuda.is_initialized()
    Resource.resources()
    helper = read(DOC/'AFFINITY_GUARD.json')
    assert helper['state'] == 'ACTIVE_RESOURCE_ONLY' and Path('/proc', str(helper['pid'])).exists()
    for f, h in p['inputs'].items():
        assert sha(f) == h, f


def setup(p):
    Prior.OUT, Prior.DOC, Prior.HERE, Prior.verify = OUT, DOC, HERE, verify
    Prior.setup(p)
    R.N.worker, R.N.inspect, Prior.O.N.inspect = Native.worker, Native.inspect, Native.inspect


def safe(row):
    return Evidence.safe(row)


def panel(p, rows):
    return Evidence.build_panel(p, rows, lambda row:R.E.N.S.arrays(row['path']))


def cached(p, guard):
    """Validate old bytes and retain original provenance; zero new physics."""
    answer = []
    queries = {q['query_key']:q for q in p['queries']}
    for entry in p['cached_measurements']:
        guard()
        original = entry['source_row']
        assert sha(original['path']) == original['sha256']
        assert original['full'] and Evidence.complete(original)
        model = p['reference'] if entry['kind'] == 'reference' else p['candidate']
        assert original['loaded_model_sha256'] == model['sha256'] and original['policy_hash'] == model['policy_hash']
        a = R.E.N.S.arrays(original['path'])
        assert all(digest(value) == original['array_hashes'][key] for key,value in a.items())
        Native.F.M.audit_full_history(p, original, a)
        q = queries[entry['query_key']]
        source = R.E.N.S.arrays(q['source_path'])
        k = q['prefix_first']
        # Nonzero reuse is only the identical reference replay, whose prefix
        # was generated by that same reference controller.
        if k:
            assert entry['kind'] == 'reference' and original['path'] == q['source_path']
        for key in ['states','poses','history_poses','history_goals','history_times']:
            assert np.array_equal(a[key][:k+1], source[key][:k+1]), key
        assert np.array_equal(a['initial_native_integration'], source['initial_native_integration'])
        assert bytes(a['scene_sha256']).hex() == q['initial_contract']['scene_sha256']
        assert np.array_equal(a['task_goal_xy'], q['initial_contract']['goal_xy'])
        if entry['kind'] == 'candidate_full':
            assert np.array_equal(a['actions'][k], np.asarray(q['candidate_action'], np.float32))
        row = dict(original, request=dict(original['request'], job=dict(q,continuation_kind=entry['kind'])),
                   role='HISTORICAL_REUSE', historical_reuse=True,
                   original_source_request=original['request'], source_exact_replay=bool(original.get('exact')),
                   additional_native_steps=0, additional_commands=0)
        row.pop('exact',None)
        answer.append(row)
    return answer


def main():
    p = plan()
    verify(p)
    setup(p)
    R.E.L.install_stop_handlers()
    lock = (ROOT / 'stage/runs/.stage_writer.lock').open('a+b')
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    assert not (OUT / 'science_started.json').exists()
    save(OUT / 'science_started.json', dict(pid=os.getpid(), epoch=time.time()))
    rt = R.Runtime(p)
    error, result = None, None
    try:
        reused = cached(p, rt.guard)
        save(OUT/'CACHED_REFERENCES.json', reused)
        rt.pool = R.N.Pool(dict(p, out=str(OUT), native_stop_epoch=rt.deadline), rt.counts, rt.guard)
        for kind, model in [('reference', p['reference']), ('candidate_once', p['reference']), ('candidate_full', p['candidate'])]:
            covered = {(r['request']['job']['query_key'],r['request']['job']['continuation_kind']) for r in reused}
            jobs = [dict(q, continuation_kind=kind) for q in p['queries'] if (q['query_key'],kind) not in covered]
            if not jobs:
                continue
            vv = rt.request(jobs, model, kind, True)
            rt.request(jobs, model, 'exact_' + kind, False, [r for a, r in vv])
        result = panel(p, reused+rt.rows)
        save(OUT / 'PANEL.json', result)
        save(OUT/'RESEARCH_DECISION.json',dict(evidence_state=result['evidence_state'],
             next_research_decision=result['next_research_decision'],automatic_learning=False,
             claim='No algorithm, sample-efficiency, gradient or navigation improvement established'))
    except BaseException:
        error = traceback.format_exc()
        save(OUT / 'failure.json', dict(error=error, no_restart=True, raw_preserved=True))
    finally:
        if rt.pool:
            rt.pool.close()
        rt.commands += 3
        save(OUT / 'summary.json', dict(state='FAILED' if error else 'COMPLETE', pid=os.getpid(), error=error,
             physics=sum(rt.counts), commands=rt.commands, elapsed_s=time.time()-rt.start,
             result=result, new_Actor=0, new_Critic=0, new_optimizer=0, full407=None, retained=p['safe_retained']))
        fcntl.flock(lock, fcntl.LOCK_UN)
        lock.close()
    assert error is None, error


def audit():
    p = plan()
    verify(p)
    setup(p)
    s = read(OUT / 'summary.json')
    assert s['state'] == 'COMPLETE' and not Path('/proc', str(s['pid'])).exists()
    for generation in read(OUT / 'worker_generations.json'):
        assert all(not Path('/proc', str(pid)).exists() for pid in [generation['parent'], *generation['workers']])
    rows = [json.loads(x) for x in gzip.decompress((OUT / 'cases.jsonl.gz').read_bytes()).decode().splitlines()]
    by = {r['path']: r for r in rows}
    assert len(rows) == len(by) == 2*p['new_measurement_count']
    for row in rows:
        assert sha(row['path']) == row['sha256']
        a = R.E.N.S.arrays(row['path'])
        kind = row['request']['job']['continuation_kind']
        model = p['candidate'] if kind == 'candidate_full' else p['reference']
        assert row['request']['model'] == model['path'] and row['loaded_model_sha256'] == model['sha256']
        assert row['policy_hash'] == model['policy_hash']
        if row['full']:
            Native.inspect(p, a, row)
        else:
            assert all(digest(v) == row['array_hashes'][key] for key, v in a.items())
        if row.get('exact'):
            ref = by[row['reference_path']]
            assert row['array_hashes'] == ref['array_hashes'] and row['integration_sha256'] == ref['integration_sha256']
    reused = cached(p,lambda:verify(p))
    assert reused == read(OUT/'CACHED_REFERENCES.json')
    assert panel(p, reused+rows) == read(OUT / 'PANEL.json') == s['result']
    assert sum(r['physics'] for r in rows) == s['physics'] <= p['max_physics']
    assert s['commands'] == len(rows) + 6 == p['max_commands']
    fresh_pairs = {(r['request']['job']['query_key'],r['request']['job']['continuation_kind']) for r in rows if not r.get('exact')}
    cached_pairs = {(r['request']['job']['query_key'],r['request']['job']['continuation_kind']) for r in reused}
    expected_pairs = {(q['query_key'],kind) for q in p['queries'] for kind in Evidence.KINDS}
    assert fresh_pairs.isdisjoint(cached_pairs) and fresh_pairs|cached_pairs == expected_pairs
    assert len(fresh_pairs) == p['new_measurement_count']
    for model in [p['reference'], p['candidate'], p['safe_retained']]:
        assert sha(model['path']) == model['sha256']
    save(OUT / 'audit.json', dict(state='PASS', all_full_causal_recurrences_and_forced_actions=True,
         every_fresh_exact_replay_verified=True, original_start_and_prefix_separated=True,
         same_candidate_first_command_and_native_hold_verified=True,
         historical_reused_entries=len(reused), new_measurements=p['new_measurement_count'],
         frozen_models_unchanged=True, new_native=0, new_optimizer=0))


if __name__ == '__main__':
    {'main': main, 'audit': audit}[sys.argv[1]]()
