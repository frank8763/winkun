from t338_core import *
from t338_worker import worker
import multiprocessing as mp

def main():
    p=read(HERE/'protocol.json');verify(p);assert not (OUT/'preflight.json').exists()
    torch.set_num_threads(1);torch.use_deterministic_algorithms(True)
    calls=[];reference=arrays(p['reference']);x=torch.tensor(reference['states'][240:256])
    rng=np.random.default_rng(p['seed']);z=torch.tensor(rng.normal(size=(len(x),2)))
    qs={arm:Learner(p,arm) for arm in p['arms']};modes=[];clone_reports=[]
    for arm,q in qs.items():
        initial=q.state();fixed=digest(q.actor.fixed.state_dict())
        with torch.no_grad():
            original=q.actor.step(x)[0];draw=q.actor.draw(x,z)
            loc,sd=q.actor.stats(x);assert torch.equal(draw['logp'],q.actor.logp(loc,sd,draw['raw_actions'],draw['atom']))
        modes.append(original)
        ctx=mp.get_context('spawn');parent,child=ctx.Pipe();os.environ['STAGE_PROCESS_CPU']='1'
        proc=ctx.Process(target=worker,args=(child,0,p,None,True));proc.start();child.close();os.environ['STAGE_PROCESS_CPU']='0'
        parent.send(dict(arm=arm,policy_np=K.S.state_np(q.actor),x=x.numpy(),z=z.numpy()));assert parent.poll(90)
        answer=parent.recv();proc.join(10);assert proc.exitcode==0 and not proc.is_alive()
        assert answer['policy_hash']==digest(q.actor.state_dict())
        assert all(np.array_equal(v.numpy(),answer['outputs'][name]) for name,v in draw.items())
        # Synthetic optimizer-only contract. These states/rewards are NOT claimed
        # to be trajectories generated by this policy and never used in main.
        fake=[]
        for j in range(4):
            a={name:v[240:256].copy() for name,v in reference.items() if name not in ['history_poses','history_goals','history_times']}
            a['end_flags'][:]=0;a['end_flags'][-1,2]=1;a['native_counts'][:]=100
            a['rewards']=np.linspace(-.01,.02,len(x))*(j+1);a['environment_rewards']=a['rewards'].copy()
            with torch.no_grad():d=q.actor.draw(x,torch.tensor(rng.normal(size=(len(x),2))))
            a.update({name:v.numpy() for name,v in d.items()});fake.append(dict(arrays=a))
        shadow=Learner(p,arm);shadow.load(initial)
        traces=[]
        for label,obj in [('live',q),('shadow',shadow)]:
            def event(row):
                calls.append(dict(arm=arm,replica=label,**row));save(OUT/'preflight_optimizer_calls.json',calls)
            traces.append(optimize(p,obj,fake,lambda:None,event,steps=1))
        assert traces[0]==traces[1] and q.hashes()==shadow.hashes()
        assert q.calls==shadow.calls==1 and fixed==digest(q.actor.fixed.state_dict())
        model=io.BytesIO();torch.save(q.state(),model);size=len(gzip.compress(model.getvalue(),mtime=0));assert size<=p['model_bytes']
        q.load(initial);assert digest(q.state())==digest(initial)
        try:optimize(p,q,fake,lambda:(_ for _ in ()).throw(InterruptedError('Synthetic before-update interrupt')),lambda _r:None,steps=1)
        except InterruptedError:pass
        else:raise AssertionError('Interrupt not exercised')
        assert digest(q.state())==digest(initial)
        clone_reports.append(dict(arm=arm,worker_all_draw_terms_exact=True,synthetic_live_shadow_Adam=2,rollback_and_interrupt_exact=True,synthetic_model_bytes=size))
    assert torch.equal(modes[0],modes[1])
    # Explicitly exercise float32 rounding at both action boundaries. Interior
    # records retain raw latent values; merged tail records use CDF mass.
    q=qs['capg'].actor;raw=torch.tensor([[-1.,1.],[-EDGE-1e-10,EDGE+1e-10],[-EDGE+1e-10,EDGE-1e-10],[0.,.5]],dtype=torch.float64)
    atom=torch.where(raw>=EDGE,1,torch.where(raw<=-EDGE,-1,0)).to(torch.int8)
    assert torch.equal(atom.abs()==1,raw.clamp(-1,1).float().abs()==1)
    loc=torch.full_like(raw,.3,requires_grad=True);sd=torch.full_like(raw,.1);value=q.logp(loc,sd,raw,atom).sum()
    grad=torch.autograd.grad(value,loc)[0];eps=1e-6
    fd=(q.logp(loc.detach()+eps,sd,raw,atom)-q.logp(loc.detach()-eps,sd,raw,atom))/(2*eps)
    assert float((grad.sum(-1)-fd).abs().max())<1e-6
    folder=OUT/'preflight';folder.mkdir();s=witness=None
    spec=importlib.util.spec_from_file_location('stage338_zero_native',ROOT/'stage/experiments/t331_policy_prefix_retry/recorder.py')
    M=importlib.util.module_from_spec(spec);spec.loader.exec_module(M);course=read(p['course_protocol']);M.install(course)
    with (folder/'factory.log').open('w') as log,contextlib.redirect_stdout(log),contextlib.redirect_stderr(log):
        try:
            native,create,witness,reward=M.setup(folder/'native')
            s=M.R.Session(course,native,create,witness,reward,lambda:None,lambda:(_ for _ in ()).throw(AssertionError('Zero physics')))
            assert s.steps==0 and s.env.max_steps==40000 and np.array_equal(s.initial120,reference['states'][0])
        finally:
            if s is not None:s.close()
            if witness is not None:witness.close()
    # Uncompressed maximum byte counts are a bound on each full NPZ payload
    # when ZIP framing is included; history and additional distribution fields.
    sample={k:v[:161] for k,v in reference.items()};sample['states']=sample['states'][:160];sample.pop('next_states')
    bound=sum(v.dtype.itemsize*int(np.prod((161 if k.startswith('history_') else 160,*v.shape[1:]))) for k,v in sample.items())
    bound+=160*(2*8*4+2+8+2*8)+2*203*8+120*4+16384
    assert bound<=p['training_episode_bytes'],bound
    save(OUT/'preflight.json',dict(state='PASS',geometry_commands=1,physics_steps=0,synthetic_discarded_Adam_calls=4,
        arm_checks=clone_reports,initial_two_arm_deterministic_actions_exact=True,float32_endpoint_rounding_mass_and_fd_exact=True,
        native80_initial120_exact=True,raw_episode_byte_bound=bound,scientific_control_not_validated=True,protocol_sha256=K.C.sha(HERE/'protocol.json')))
    verify(p);print('T338 preflight PASS:0physics,4discardedAdam,actualworker density/exactshadow/rollback/native80')

if __name__=='__main__':
    try:main()
    except BaseException:
        save(OUT/'preflight_failure.json',dict(error=traceback.format_exc(),physics_steps=0));raise
